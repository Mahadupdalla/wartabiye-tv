// Copies the publishing tool (Sveltia CMS) and its configuration from the website repository into public/cms/,
// pointing it at this Worker's GitHub proxy instead of api.github.com. Run before every deploy (the workflow does it),
// so changes to admin/config.yml reach the secure dashboard automatically.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const pub = join(here, '..', 'public');

function patch(yml, back) {
  // only the backend block changes: the GitHub calls go to /api/github on this Worker (session-checked, token added there)
  const lines = yml.split('\n');
  const i = lines.findIndex(l => /^backend:\s*$/.test(l));
  if (i < 0) throw new Error('backend: block not found');
  if (!lines.some((l, k) => k > i && /^\s+name:\s*github\s*$/.test(l))) throw new Error('github backend not found');
  // __ORIGIN__ is replaced by the Worker's own address when the file is served (GitHub Enterprise style paths)
  lines.splice(i + 1, 0, "  api_root: __ORIGIN__/api/github/api/v3", "  graphql_api_root: __ORIGIN__/api/github/api/graphql");
  let out = lines.join('\n');
  out = out.replace(/^(\s*src:\s*)\.\.\/(\.\.\/)?img\/logo\.png\s*$/m, '$1' + back + 'brand/logo.png');
  return '# Generated by workers/admin/scripts/prepare.mjs from the website repository. Do not edit here.\n' + out;
}

mkdirSync(join(pub, 'cms', 'vendor'), { recursive: true });
mkdirSync(join(pub, 'cms', 'codsiyada'), { recursive: true });
mkdirSync(join(pub, 'brand'), { recursive: true });
const vendor = readdirSync(join(root, 'admin', 'vendor'));
for (const f of vendor) copyFileSync(join(root, 'admin', 'vendor', f), join(pub, 'cms', 'vendor', f));
const js = vendor.find(f => /^sveltia-cms-[\d.]+\.js$/.test(f));
if (!js) throw new Error('Sveltia CMS bundle not found in admin/vendor');
// the two CMS pages load whichever Sveltia version the website repository ships
for (const page of [join(pub, 'cms', 'index.html'), join(pub, 'cms', 'codsiyada', 'index.html')]) {
  writeFileSync(page, readFileSync(page, 'utf8').replace(/\/cms\/vendor\/sveltia-cms-[\d.]+\.js/, '/cms/vendor/' + js));
}
writeFileSync(join(pub, 'cms', 'config.yml'), patch(readFileSync(join(root, 'admin', 'config.yml'), 'utf8'), '/'));
writeFileSync(join(pub, 'cms', 'codsiyada', 'config.yml'), patch(readFileSync(join(root, 'admin', 'codsiyada', 'config.yml'), 'utf8'), '/'));
copyFileSync(join(root, 'img', 'logo.png'), join(pub, 'brand', 'logo.png'));
console.log('prepared public/cms with', js);
